// Pure builders for every docker command the runner issues. Kept free of I/O so the sealing model is unit-tested
// on the exact argv: an adapter container gets the brief (read-only) and its out/ folder, and nothing else.
import YAML from 'yaml';

/** Paths inside every adapter container. */
export const BENCH_BRIEF_DIR = '/bench/brief';
export const BENCH_OUT_DIR = '/bench/out';
export const BENCH_BRIEF_FILE = `${BENCH_BRIEF_DIR}/brief.json`;
export const BENCH_FINDINGS_FILE = `${BENCH_OUT_DIR}/findings.json`;
export const BENCH_EVIDENCE_DIR = `${BENCH_OUT_DIR}/evidence`;

/** Fixed, non-secret env every adapter gets (in addition to its manifest's env_passthrough names). */
export const ADAPTER_FIXED_ENV: Record<string, string> = {
  QA_BENCH_BRIEF: BENCH_BRIEF_FILE,
  QA_BENCH_OUT: BENCH_OUT_DIR,
};

/** Host env that docker and compose themselves need. Nothing else from the host reaches them. */
const DOCKER_ENV_KEYS = [
  'PATH', 'HOME', 'USER', 'TMPDIR', 'XDG_RUNTIME_DIR', 'XDG_CONFIG_HOME',
  'DOCKER_HOST', 'DOCKER_CONFIG', 'DOCKER_CONTEXT', 'DOCKER_CERT_PATH', 'DOCKER_TLS_VERIFY', 'DOCKER_BUILDKIT',
  'BUILDX_CONFIG', 'BUILDKIT_PROGRESS', 'COMPOSE_PROGRESS', 'SSL_CERT_FILE',
];
const PROXY_KEYS = ['HTTPS_PROXY', 'HTTP_PROXY', 'NO_PROXY', 'https_proxy', 'http_proxy', 'no_proxy'];

export function pickEnv(host: NodeJS.ProcessEnv, keys: readonly string[]): NodeJS.ProcessEnv {
  const out: NodeJS.ProcessEnv = {};
  for (const k of keys) if (host[k] !== undefined) out[k] = host[k];
  return out;
}

/**
 * Minimal env for docker/compose. Compose lets the shell override --env-file values, so the host's own env must
 * never reach it: a stray DEFECT=... on the host would otherwise switch on a defect.
 */
export function dockerEnv(host: NodeJS.ProcessEnv, extra: readonly string[] = []): NodeJS.ProcessEnv {
  return pickEnv(host, [...DOCKER_ENV_KEYS, ...extra]);
}

export interface BuildSpec {
  tag: string;
  context: string;
  dockerfile: string;
}

/**
 * `docker build` argv. With QA_BENCH_BUILD_CA set (a PEM path), the build uses the host network, gets the CA as
 * an optional BuildKit secret (never baked into the image) and the proxy settings as build args, passed by name
 * so their values never appear on the command line.
 */
export function buildArgs(spec: BuildSpec, host: NodeJS.ProcessEnv): { args: string[]; env: NodeJS.ProcessEnv } {
  const args = ['build', '-t', spec.tag, '-f', spec.dockerfile];
  const ca = host.QA_BENCH_BUILD_CA;
  const extra: string[] = [];
  if (ca) {
    args.push('--network', 'host', '--secret', `id=extra_ca,src=${ca}`);
    for (const k of ['HTTPS_PROXY', 'HTTP_PROXY', 'NO_PROXY']) {
      if (host[k]) {
        args.push('--build-arg', k);
        extra.push(k);
      }
    }
  }
  args.push(spec.context);
  return { args, env: dockerEnv(host, extra.length ? [...extra, ...PROXY_KEYS] : []) };
}

/** Compose project name: lowercase letters, digits, '-' and '_' only, starting with a letter or digit. */
export function projectName(prefix: string, runId: string, episodeId: string): string {
  return `${prefix}-${runId}-${episodeId}`.toLowerCase().replace(/[^a-z0-9_-]+/g, '-').replace(/^[^a-z0-9]+/, '');
}

export function composeBase(project: string, files: string[], envFile: string): string[] {
  return ['compose', '-p', project, ...files.flatMap((f) => ['-f', f]), '--env-file', envFile];
}

export function composeUpArgs(base: string[], waitTimeoutS = 180): string[] {
  return [...base, 'up', '-d', '--no-build', '--wait', '--wait-timeout', String(waitTimeoutS)];
}

export function composeDownArgs(base: string[]): string[] {
  return [...base, 'down', '-v', '--remove-orphans', '-t', '5'];
}

/**
 * Compose override for adapters with network "host": publish each target port on 127.0.0.1 with an ephemeral
 * host port (read back with `docker compose port`). Nothing is published on other interfaces.
 */
export function hostPortOverride(targets: { service: string; port: number }[]): string {
  const services: Record<string, { ports: string[] }> = {};
  for (const t of targets) {
    const s = (services[t.service] ??= { ports: [] });
    const spec = `127.0.0.1::${t.port}`;
    if (!s.ports.includes(spec)) s.ports.push(spec);
  }
  return '# Generated by the qa-bench runner for an adapter with network "host".\n' + YAML.stringify({ services });
}

/** Parse `docker compose port` output ("127.0.0.1:49153") to a port number. */
export function parsePublishedPort(stdout: string): number | undefined {
  const line = stdout.trim().split('\n').pop() ?? '';
  const m = /:(\d+)$/.exec(line.trim());
  return m ? Number(m[1]) : undefined;
}

/** A compose --env-file. Values are written raw when safe, single-quoted otherwise. */
export function envFileText(env: Record<string, string>): string {
  const lines: string[] = [];
  for (const key of Object.keys(env).sort()) {
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)) throw new Error(`env key '${key}' is not a valid name`);
    const value = env[key] as string;
    if (/^[A-Za-z0-9_.:,@/+=%-]*$/.test(value)) lines.push(`${key}=${value}`);
    else if (!/['\n\r]/.test(value)) lines.push(`${key}='${value}'`);
    else throw new Error(`env value for '${key}' cannot be written to an env file`);
  }
  return lines.join('\n') + '\n';
}

export interface AdapterRunSpec {
  containerName: string;
  image: string;
  /** Docker network to join: the episode's compose network, 'host', or 'bridge' (live sites). */
  network: string;
  /** Host path of <ep>/brief, mounted read-only. */
  briefDir: string;
  /** Host path of <ep>/out, mounted read-write. */
  outDir: string;
  /** Host env var names to pass through (values come from the runner's env, never the command line). */
  envPassthrough: string[];
  command?: string[];
}

/**
 * `docker run` argv for an adapter. This is the sealing boundary (AGENTS.md rule 8): exactly two mounts, the brief
 * read-only and out/ read-write; env only by name from the manifest's allow-list plus fixed bench paths. The repo,
 * apps/, episodes/ and answer keys are never mounted.
 */
export function adapterRunArgs(spec: AdapterRunSpec): string[] {
  const args = [
    'run', '--rm',
    '--name', spec.containerName,
    '--network', spec.network,
    '--security-opt', 'no-new-privileges',
    '--shm-size', '1g',
    '-v', `${spec.briefDir}:${BENCH_BRIEF_DIR}:ro`,
    '-v', `${spec.outDir}:${BENCH_OUT_DIR}`,
  ];
  for (const [k, v] of Object.entries(ADAPTER_FIXED_ENV)) args.push('-e', `${k}=${v}`);
  for (const name of [...new Set(spec.envPassthrough)].sort()) {
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) throw new Error(`env_passthrough name '${name}' is not a valid name`);
    args.push('-e', name);
  }
  args.push(spec.image, ...(spec.command ?? []));
  return args;
}

/** Argv for logging: build-arg and env entries keep their names only. */
export function redactArgs(args: string[]): string {
  return args.map((a, i) => (args[i - 1] === '-e' || args[i - 1] === '--build-arg' ? a.replace(/=.*/, '=…') : a)).join(' ');
}
